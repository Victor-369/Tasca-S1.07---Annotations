package com.pruebas.proyecto.nivell2.exercici1;

@JsonSerializable(destinationDirectory = "output")
public class Person {
    private String name;
    private int age;

    public Person(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }
}
